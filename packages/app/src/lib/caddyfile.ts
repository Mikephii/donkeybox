import type { AuthMode } from "../env.ts";
import type { Settings } from "../engine/config.ts";

export interface CaddyPorts {
  appDoor: number;
  /** 0: webhooks share the app door (local dev). Otherwise a separate public listener. */
  hooksDoor: number;
  app: number;
  hooks: number;
  yjs: number;
  zellijWeb: number;
  codeServer: number;
  /** Set in dev: the frontend comes from Vite instead of the app. */
  vite: number | null;
  /** Ports that previews must never reach (loopback API, management, supervisor, internals). */
  blocked: number[];
  /** Address the doors listen on: 127.0.0.1 on a laptop, empty (every interface) in a container. */
  bind?: string;
}

const site = (hosts: string[], port: number) => (hosts.length ? hosts.map((h) => `http://${h}:${port}`).join(", ") : `:${port}`);

/**
 * The box's door configuration, generated from settings and the identity mode. Every route that the
 * app does not answer itself (terminals, sync, previews, code-server, devtools) asks the app's
 * /auth/check first, so nothing behind the door is reachable without a verified identity.
 */
export function caddyfile(settings: Settings, mode: AuthMode, p: CaddyPorts, opts: { codeServer: boolean }): string {
  const d = settings.doors;
  // private: only the private networks; both: those plus the identity proxy's addresses. Webhooks
  // always stay reachable, since senders like GitHub are on the internet.
  const allowed = d.appAccess === "private" ? d.privateCidrs : d.appAccess === "both" ? [...d.privateCidrs, ...settings.auth.proxy.trustedCidrs] : [];
  const restrict = allowed.length
    ? `\t@outside {\n\t\tnot remote_ip ${allowed.join(" ")}\n\t\tnot path /hooks/*\n\t}\n\trespond @outside "This door only accepts the private network." 403\n`
    : "";
  // Identity headers only ever come from the door's own check, never from the client.
  // X-Wb-Peer: the client's address as the door saw it, for proxy mode's trusted networks.
  const bindLine = p.bind ? `\tbind ${p.bind}\n` : "";
  const strip = `${bindLine}\trequest_header -X-Wb-Email\n\trequest_header -X-Wb-Role\n\trequest_header X-Wb-Peer {remote_host}\n`;
  const blocked = [...new Set([...p.blocked, p.app, p.hooks, p.yjs, p.zellijWeb, p.codeServer])].join("|");
  const gate = `\t\tforward_auth 127.0.0.1:${p.app} {\n\t\t\turi /auth/check\n\t\t\tcopy_headers X-Wb-Email X-Wb-Role\n\t\t}\n`;
  const hooksInline =
    p.hooksDoor === 0
      ? `\thandle /hooks/* {\n\t\trequest_body {\n\t\t\tmax_size 2MB\n\t\t}\n\t\treverse_proxy 127.0.0.1:${p.hooks}\n\t}\n`
      : "";
  // With the editor not running, /code still gets an answer of its own: falling through to the app
  // would load the workbench inside the Editor window.
  const code = opts.codeServer
    ? `\thandle_path /code/* {\n${gate}\t\treverse_proxy 127.0.0.1:${p.codeServer}\n\t}\n\tredir /code /code/ 308\n`
    : `\thandle /code* {\n\t\trespond "The editor is not running." 503\n\t}\n`;
  const front = p.vite ? `127.0.0.1:${p.vite}` : `127.0.0.1:${p.app}`;
  const app = `${site(d.appHosts, p.appDoor)} {
${strip}${restrict}\tredir /term /term/ 308
\thandle_path /term/* {
${gate}\t\treverse_proxy 127.0.0.1:${p.zellijWeb} {
\t\t\theader_down X-Frame-Options SAMEORIGIN
\t\t}
\t}
\thandle /yjs* {
${gate}\t\treverse_proxy 127.0.0.1:${p.yjs}
\t}
\t@blocked path_regexp ^/p/(${blocked})(/.*)?$
\thandle @blocked {
\t\trespond "not exposed" 403
\t}
\t@preview path_regexp preview ^/p/(\\d+)(/.*)?$
\thandle @preview {
${gate}\t\turi strip_prefix /p/{re.preview.1}
\t\treverse_proxy 127.0.0.1:{re.preview.1}
\t}
\thandle_path /devtools/* {
${gate}\t\treverse_proxy 127.0.0.1:9222 {
\t\t\theader_up Host localhost
\t\t}
\t}
${code}${hooksInline}\thandle /api/* {
\t\treverse_proxy 127.0.0.1:${p.app}
\t}
\thandle /auth/* {
\t\treverse_proxy 127.0.0.1:${p.app}
\t}
\thandle {
\t\treverse_proxy ${front}
\t}
}
`;
  const hooks =
    p.hooksDoor > 0
      ? `
${site(d.hooksHosts, p.hooksDoor)} {
${bindLine}\t@hook {
\t\tmethod POST
\t\tpath /hooks/*
\t}
\thandle @hook {
\t\trequest_body {
\t\t\tmax_size 2MB
\t\t}
\t\treverse_proxy 127.0.0.1:${p.hooks}
\t}
\trespond 404
}
`
      : "";
  return `# Generated by the workbench from settings.doors and AUTH_MODE=${mode}. Do not edit; change Settings instead.
{
\tadmin off
\tauto_https off
\tpersist_config off
}

${app}${hooks}`;
}
