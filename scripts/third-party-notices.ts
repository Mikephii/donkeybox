// Generates THIRD_PARTY_NOTICES.md from the production dependency tree (pnpm) plus the programs the
// image bundles or installs. Run after changing dependencies: pnpm notices
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const versions = JSON.parse(readFileSync(join(ROOT, "versions.json"), "utf8"));
type Node = { from?: string; version: string; path: string; dependencies?: Record<string, Node> };
const tree = JSON.parse(execFileSync("pnpm", ["ls", "-r", "--prod", "--json", "--depth", "Infinity"], { cwd: ROOT, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 })) as { name: string; dependencies?: Record<string, Node> }[];

const pkgs = new Map<string, { name: string; version: string; path: string }>();
const walk = (deps: Record<string, Node> | undefined) => {
  for (const [name, n] of Object.entries(deps ?? {})) {
    if (!n.path || n.version.startsWith("link:")) continue;
    const key = `${name}@${n.version}`;
    if (pkgs.has(key)) continue;
    pkgs.set(key, { name, version: n.version, path: n.path });
    walk(n.dependencies);
  }
};
for (const p of tree) walk(p.dependencies);

const licenseText = (dir: string) => {
  const f = existsSync(dir) ? readdirSync(dir).find((x) => /^(licen[sc]e|copying)(\.|$|-)/i.test(x)) : undefined;
  return f ? readFileSync(join(dir, f), "utf8").trim() : null;
};
const rows = [...pkgs.values()].sort((a, b) => a.name.localeCompare(b.name)).map((p) => {
  const pj = JSON.parse(readFileSync(join(p.path, "package.json"), "utf8"));
  const license = typeof pj.license === "string" ? pj.license : pj.license?.type ?? (Array.isArray(pj.licenses) ? pj.licenses.map((l: any) => l.type).join(" OR ") : "UNKNOWN");
  const repo = typeof pj.repository === "string" ? pj.repository : pj.repository?.url ?? pj.homepage ?? "";
  return { ...p, license, repo: String(repo).replace(/^git\+/, "").replace(/\.git$/, ""), text: licenseText(p.path) };
});

const counts = new Map<string, number>();
for (const r of rows) counts.set(r.license, (counts.get(r.license) ?? 0) + 1);

const programs = [
  ["Zellij", versions.zellij, "MIT", "https://github.com/zellij-org/zellij", "bundled in the image and installed by setup"],
  ["Caddy", versions.caddy, "Apache-2.0", "https://github.com/caddyserver/caddy", "bundled in the image and installed by setup"],
  ["Node.js", versions.node, "MIT (and bundled third-party licences)", "https://nodejs.org", "the image's base runtime"],
  ["code-server", versions.codeServer, "MIT", "https://github.com/coder/code-server", "installed on request with wb tools install code-server; not bundled"],
  ["Claude Code", versions.claudeCode, "Anthropic commercial terms", "https://www.anthropic.com/legal", "installed by each box's owner with wb tools install claude-code and signed in with their own account; not bundled or redistributed"],
  ["oauth2-proxy", "7.7.1", "MIT", "https://github.com/oauth2-proxy/oauth2-proxy", "referenced by deploy/compose as a separate container image"],
  ["Debian (container base)", "bookworm", "various free licences", "https://www.debian.org/legal/licenses/", "base image packages: git, openssh-client, curl, tini, bash and their dependencies"],
];

let out = `# Third-party notices

Generated by \`pnpm notices\` (scripts/third-party-notices.ts) from the production dependency tree.
Do not edit by hand.

## Programs the box runs

| Program | Version | Licence | Source | How it is used |
|---|---|---|---|---|
${programs.map((p) => `| ${p.join(" | ")} |`).join("\n")}

## npm packages (${rows.length})

Licences: ${[...counts].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} ${n}`).join(", ")}.

| Package | Version | Licence | Source |
|---|---|---|---|
${rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.repo} |`).join("\n")}

## Licence texts

`;
for (const r of rows) out += `### ${r.name}@${r.version} (${r.license})\n\n${r.text ? "```\n" + r.text.replace(/```/g, "'''") + "\n```" : "No licence file is shipped in the package; see its package.json and source."}\n\n`;
writeFileSync(join(ROOT, "THIRD_PARTY_NOTICES.md"), out);
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages; licences ${[...counts].map(([l, n]) => `${l}=${n}`).join(", ")}`);
